export type Shot = {
  src: string;
  caption: string;
  fileHint: string;
  fit?: "cover" | "contain";
};

function shot(file: string, caption = "", fit?: Shot["fit"]): Shot {
  return { src: `/${encodeURIComponent(file)}`, caption, fileHint: file, fit };
}

